local function font(name, path, size, flags, color, shadow, justify)
	local f = CreateFont(name)
	local s = S[f]
	s.fontPath, s.fontSize, s.fontFlags = path, size, flags or ""
	s.textColor = color and { color[1], color[2], color[3], color[4] } or { 1, 1, 1, 1 }
	if shadow ~= false then
		s.shadowColor = { 0, 0, 0, 1 }
		s.shadowOffset = { 1, -1 }
	end
	s.justifyH = justify
	return f
end

